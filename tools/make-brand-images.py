"""Builds the website's raster brand images from the official Starlit artwork.

    python tools/make-brand-images.py --app <path to a starlit checkout>

Inputs come from the app repository (all generated by its
branding/generate_brand_assets.py):
  branding/readme/starlit-wordmark-dark.png    wordmark for dark backgrounds
  branding/readme/starlit-wordmark-light.png   wordmark for light backgrounds
  composeApp/src/desktopMain/resources/icons/app-icon-original-transparent.png
  branding/starlit-mark.svg                    copied unchanged

Outputs (committed, so building the site needs only Node):
  assets/starlit-mark.svg, assets/starlit-wordmark-{dark,light}.png,
  assets/og-image.png, assets/icons/apple-touch-icon.png, assets/icons/favicon.ico

Requires Python 3 and Pillow. The artwork itself is never redrawn: images are
resized and placed on the site's night-sky colours only.
"""

from __future__ import annotations

import argparse
import random
import shutil
from pathlib import Path

from PIL import Image, ImageDraw

SITE = Path(__file__).resolve().parents[1]
ASSETS = SITE / "assets"
MIDNIGHT = (10, 14, 39)
DEEP = (24, 30, 78)


def sparkle_points(cx: float, cy: float, rx: float, ry: float, waist: float = 0.12, steps: int = 10):
    """The mark's four-point star (quadratic sides pinched to the centre) as a polygon."""
    kx, ky = rx * waist, ry * waist
    corners = [(cx, cy - ry), (cx + rx, cy), (cx, cy + ry), (cx - rx, cy)]
    controls = [(cx + kx, cy - ky), (cx + kx, cy + ky), (cx - kx, cy + ky), (cx - kx, cy - ky)]
    points = []
    for i in range(4):
        (x0, y0), (x1, y1), (x2, y2) = corners[i], controls[i], corners[(i + 1) % 4]
        for s in range(steps):
            t = s / steps
            points.append(((1 - t) ** 2 * x0 + 2 * (1 - t) * t * x1 + t * t * x2,
                           (1 - t) ** 2 * y0 + 2 * (1 - t) * t * y1 + t * t * y2))
    return points


def night_sky(width: int, height: int, clear: tuple[int, int, int, int] | None = None,
              seed: int = 20261105) -> Image.Image:
    """Stars avoid `clear` (left, top, right, bottom), the logo's clear space."""
    scale = 2
    w, h = width * scale, height * scale
    sky = Image.new("RGB", (w, h), MIDNIGHT)
    draw = ImageDraw.Draw(sky)
    for y in range(h):  # gentle lift towards the lower edge
        t = (y / h) ** 1.6
        draw.line([(0, y), (w, y)], fill=tuple(round(a + (b - a) * t) for a, b in zip(MIDNIGHT, DEEP)))
    stars = Image.new("L", (w, h), 0)
    sdraw = ImageDraw.Draw(stars)
    rnd = random.Random(seed)

    def blocked(x: float, y: float) -> bool:
        return bool(clear) and clear[0] * scale <= x <= clear[2] * scale and clear[1] * scale <= y <= clear[3] * scale

    for _ in range(220):
        x, y = rnd.random() * w, rnd.random() * h
        r = (0.6 + rnd.random() * rnd.random() * 1.8) * scale
        alpha = round(255 * (0.2 + rnd.random() * 0.6))
        if not blocked(x, y):
            sdraw.ellipse([x - r, y - r, x + r, y + r], fill=alpha)
    for _ in range(16):
        x, y = rnd.random() * w, rnd.random() * h
        s = (5 + rnd.random() * rnd.random() * 14) * scale
        alpha = round(255 * (0.4 + rnd.random() * 0.5))
        if not blocked(x, y):
            sdraw.polygon(sparkle_points(x, y, s, s * 1.17), fill=alpha)
    sky.paste((255, 255, 255), (0, 0), stars)
    return sky.resize((width, height), Image.LANCZOS)


def fit_height(image: Image.Image, height: int) -> Image.Image:
    return image.resize((round(image.width * height / image.height), height), Image.LANCZOS)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--app", type=Path, required=True, help="starlit checkout")
    app = parser.parse_args().app
    dark = Image.open(app / "branding/readme/starlit-wordmark-dark.png").convert("RGBA")
    light = Image.open(app / "branding/readme/starlit-wordmark-light.png").convert("RGBA")
    icon = Image.open(app / "composeApp/src/desktopMain/resources/icons/app-icon-original-transparent.png").convert("RGBA")

    (ASSETS / "icons").mkdir(parents=True, exist_ok=True)
    shutil.copyfile(app / "branding/starlit-mark.svg", ASSETS / "starlit-mark.svg")

    # Header and footer show the wordmark 32px tall; ship it at 3x.
    for name, image in (("dark", dark), ("light", light)):
        fit_height(image, 96).save(ASSETS / f"starlit-wordmark-{name}.png", optimize=True)

    # Social preview: the official wordmark centred on the site's night sky.
    mark = fit_height(dark, 170)
    left, top = (1200 - mark.width) // 2, (630 - mark.height) // 2 - 6
    pad = 56
    og = night_sky(1200, 630, clear=(left - pad, top - pad, left + mark.width + pad, top + mark.height + pad))
    og.paste(mark, (left, top), mark)
    og.convert("RGB").save(ASSETS / "og-image.png", optimize=True)

    touch = Image.new("RGBA", (180, 180), MIDNIGHT + (255,))
    glyph = icon.resize((156, 156), Image.LANCZOS)
    touch.paste(glyph, (12, 12), glyph)
    touch.convert("RGB").save(ASSETS / "icons/apple-touch-icon.png", optimize=True)

    icon.save(ASSETS / "icons/favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)])
    print("Brand images written to", ASSETS)


if __name__ == "__main__":
    main()
