#!/usr/bin/env node
// Builds the Starlit account dashboard into account/dist/.
// This app can run standalone at / or under /account/ alongside the public
// marketing pages without weakening the marketing Content-Security-Policy.
//
//   node build.mjs                 mock API with synthetic data (default)
//   node build.mjs --mode=live     real account API; needs STARLIT_ANON_KEY
//
// Live builds are read-only unless STARLIT_ACCOUNT_WRITES=1, so the editor can
// be rolled out behind a flag after the staged read checks pass.
import { cpSync, existsSync, lstatSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, isAbsolute, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, 'src');
// STARLIT_ACCOUNT_OUT lets tests build into a temporary folder.
const defaultDist = join(here, 'dist');
const customOut = process.env.STARLIT_ACCOUNT_OUT;
const dist = customOut ? resolve(customOut) : defaultDist;
const siteAssets = join(here, '..', 'assets');

const fail = message => { console.error(`Account build refused: ${message}`); process.exit(1); };
// Only the known, ignored default dist is replaceable. A custom location is
// only ever filled when empty, never recursively deleted, and may not point
// into the website's source tree. This prevents a mistyped OUT from erasing
// arbitrary source or user files.
const inside = (parent, child) => {
  const diff = relative(parent, child);
  return diff === '' || (diff !== '..' && !diff.startsWith('..' + sep) && !isAbsolute(diff));
};
if (customOut && inside(join(here, '..'), dist)) fail('custom output must be outside the website repository');
if (existsSync(dist) && lstatSync(dist).isSymbolicLink()) fail('output must not be a symlink');
if (customOut && existsSync(dist) && (!lstatSync(dist).isDirectory() || readdirSync(dist).length)) {
  fail('custom output directory must be empty');
}
const arg = name => process.argv.find(a => a.startsWith(`--${name}=`))?.slice(name.length + 3);

const mode = arg('mode') ?? process.env.STARLIT_ACCOUNT_MODE ?? 'mock';
const basePath = process.env.STARLIT_ACCOUNT_BASE_PATH ?? '/';
if (!/^\/(?:[a-z0-9-]+\/)*$/.test(basePath) || basePath.includes('//')) {
  fail('STARLIT_ACCOUNT_BASE_PATH must be an absolute directory path ending in /');
}
if (!['mock', 'live'].includes(mode)) fail(`unknown mode "${mode}"`);

const apiUrl = (process.env.STARLIT_API_URL ?? 'https://starlit-api.rrmtools.uk').replace(/\/+$/, '');
const anonKey = (process.env.STARLIT_ANON_KEY ?? '').trim();
const writes = mode === 'mock' || process.env.STARLIT_ACCOUNT_WRITES === '1';
const google = mode === 'live' && process.env.STARLIT_GOOGLE_SIGNIN === '1';
const passkey = mode === 'live' && process.env.STARLIT_PASSKEY_SIGNIN === '1';

// The browser may only ever hold the public anon key. Refuse anything else.
function checkPublicKey(key) {
  const parts = key.split('.');
  if (parts.length !== 3 || !parts.every(p => /^[A-Za-z0-9_-]*$/.test(p))) return 'STARLIT_ANON_KEY is not a JWT';
  let claims;
  try { claims = JSON.parse(Buffer.from(parts[1], 'base64url').toString('utf8')); }
  catch { return 'STARLIT_ANON_KEY payload is unreadable'; }
  if (claims.role !== 'anon') return 'STARLIT_ANON_KEY must be the public anon key (role "anon"); service keys never go to a browser';
  return null;
}

if (mode === 'live') {
  if (!/^https:\/\/[a-z0-9.-]+$/i.test(apiUrl)) fail('STARLIT_API_URL must be an https origin');
  if (!anonKey) fail('live mode needs STARLIT_ANON_KEY (the public anon key)');
  const problem = checkPublicKey(anonKey);
  if (problem) fail(problem);
}

if (!customOut) rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

// Copy the app. The mock API and its synthetic fixtures never ship in a live build.
cpSync(src, dist, {
  recursive: true,
  filter: from => mode === 'mock' || !from.split(/[/\\]/).includes('mock'),
});

// Prefix document assets when the account UI is mounted under /account/.
// Absolute paths avoid incorrect asset loads on deeply nested SPA routes.
if (basePath !== '/') {
  const indexPath = join(dist, 'index.html');
  let html = readFileSync(indexPath, 'utf8');
  for (const name of ['/favicon.ico', '/fonts/', '/styles/', '/app.js']) {
    html = html.replaceAll('"' + name, '"' + basePath + name.slice(1));
  }
  writeFileSync(indexPath, html);
  const cssPath = join(dist, 'styles', 'account.css');
  writeFileSync(cssPath, readFileSync(cssPath, 'utf8').replaceAll('url(/fonts/', 'url(' + basePath + 'fonts/'));
}

const config = {
  mode,
  basePath,
  apiUrl: mode === 'live' ? apiUrl : '',
  anonKey: mode === 'live' ? anonKey : 'mock-anon-key',
  writesEnabled: writes,
  googleSignIn: google,
  passkeySignIn: passkey,
  siteUrl: 'https://starlit.rrmtools.uk',
};
writeFileSync(join(dist, 'config.js'),
  `// Generated by build.mjs. Public values only.\nexport const config = Object.freeze(${JSON.stringify(config, null, 2)});\n`);
writeFileSync(join(dist, 'transport.js'), mode === 'mock'
  ? `// Generated: synthetic in-browser API. Not connected to any Starlit account.\nexport { transport } from './mock/transport.js';\nexport { mountMockPanel } from './mock/panel.js';\n`
  : `// Generated: the real account API.\nexport const transport = (url, init) => globalThis.fetch(url, init);\nexport const mountMockPanel = null;\n`);

// Reuse the website's self-hosted, OFL-licensed fonts and mark (copied at build time, never edited).
mkdirSync(join(dist, 'fonts'), { recursive: true });
for (const file of readdirSync(join(siteAssets, 'fonts'))) {
  if (/\.(woff2|txt)$/.test(file) && !/mona|source-serif/i.test(file)) cpSync(join(siteAssets, 'fonts', file), join(dist, 'fonts', file));
}
cpSync(join(siteAssets, 'starlit-mark.svg'), join(dist, 'starlit-mark.svg'));
if (existsSync(join(siteAssets, 'icons', 'favicon.ico'))) cpSync(join(siteAssets, 'icons', 'favicon.ico'), join(dist, 'favicon.ico'));

const connect = mode === 'live' ? `'self' ${apiUrl}` : `'self'`;
const csp = [
  "default-src 'none'",
  "script-src 'self'",
  "style-src 'self'",
  // Artwork previews are user-chosen https images, loaded only when asked for.
  "img-src 'self' https: data:",
  "font-src 'self'",
  `connect-src ${connect}`,
  "manifest-src 'self'",
  "object-src 'none'",
  "form-action 'none'",
  "frame-ancestors 'none'",
  "base-uri 'none'",
  'upgrade-insecure-requests',
].join('; ');

writeFileSync(join(dist, '_headers'), `/*
  Strict-Transport-Security: max-age=31536000
  X-Content-Type-Options: nosniff
  Referrer-Policy: no-referrer
  X-Frame-Options: DENY
  X-Robots-Tag: noindex, nofollow
  Cross-Origin-Opener-Policy: same-origin
  Cross-Origin-Resource-Policy: same-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()
  Content-Security-Policy: ${csp}
  Cache-Control: no-cache, no-transform
/fonts/*
  Cache-Control: public, max-age=31536000, immutable
`);

// The VPS Caddy static server serves index.html for unknown frontend routes.
// Keep 404.html absent so static and preview behavior do not diverge.
if (existsSync(join(dist, '404.html'))) fail('dist/404.html would disable single-page routing');

const count = readdirSync(dist, { recursive: true }).length;
console.log(`Built the account dashboard (${mode}${mode === 'live' && !writes ? ', read-only' : ''}) with ${count} files in ${dist}`);
